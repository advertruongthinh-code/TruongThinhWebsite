// Slot keys of the standard pages (cms-plan part 2 K7, task E6).
//   node scripts/cms/assign-slots.mjs [page…]  writes data-slot on every slot target of the named pages (once per page), then
//                                              refreshes tests/site/fixtures/slots.json and src/cms/slots.generated.mjs.
//   node scripts/cms/assign-slots.mjs --check  fails when a page's data-slot keys differ from the fixture.
// Keys live in the HTML after the first run: a new section sets its own data-slot and updates the fixture in the same PR.
import { readFileSync, writeFileSync } from "node:fs";
import { SLOT_PAGES, slotIds, slotsOf } from "../site/slots.mjs";

const root = new URL("../../", import.meta.url);
const read = (file) => readFileSync(new URL(file, root), "utf8");
const fixtureFile = "tests/site/fixtures/slots.json";
const fixture = JSON.parse(read(fixtureFile));
const args = process.argv.slice(2);

if (args[0] === "--check") {
  const errors = Object.entries(fixture).flatMap(([id, expected]) => {
    const actual = JSON.stringify(slotsOf(read(`src/site/${SLOT_PAGES[id]}`)));
    return actual === JSON.stringify(expected) ? [] : [`${SLOT_PAGES[id]}: data-slot keys differ from ${fixtureFile}`];
  });
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  console.log(`slots: ${Object.keys(fixture).length} pages match ${fixtureFile}`);
} else {
  for (const id of args) {
    const file = `src/site/${SLOT_PAGES[id]}`;
    let html = read(file);
    if (html.includes("data-slot=")) throw new Error(`${file} already has slots: keys are set once, then edited by hand`);
    for (const { element, id: slot } of slotIds(html).toReversed()) {
      const at = element.start + 1 + element.name.length;
      html = `${html.slice(0, at)} data-slot="${slot}"${html.slice(at)}`;
    }
    writeFileSync(new URL(file, root), html.replace(/\n\s*data-cms="[^"]*"/g, ""));
    fixture[id] = slotsOf(html);
  }
  const ordered = Object.fromEntries(Object.keys(SLOT_PAGES).filter((id) => fixture[id]).map((id) => [id, fixture[id]]));
  writeFileSync(new URL(fixtureFile, root), `${JSON.stringify(ordered, null, 2)}\n`);
  const slots = Object.fromEntries(Object.entries(ordered).map(([id, list]) => [id, Object.fromEntries(list.map(({ id: key, ...rest }) => [key, rest]))]));
  writeFileSync(new URL("src/cms/slots.generated.mjs", root), `// Generated by scripts/cms/assign-slots.mjs from ${fixtureFile}: the slots of each page-copy record (K7). Do not edit.\nexport const SLOTS = ${JSON.stringify(slots, null, 2)};\n`);
}
