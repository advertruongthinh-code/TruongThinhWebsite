// Builds DESIGN.md and the .impeccable/design.json sidecar for Impeccable from design-system/ (docs/specs/docs-system.md R6).
// Usage: node scripts/docs/build-design-md.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { posix } from 'node:path';

const tokens = JSON.parse(readFileSync('design-system/tokens.json', 'utf8'));
const readme = readFileSync('design-system/README.md', 'utf8');
const title = `Design System: ${tokens.name}`;
// JSON strings are valid YAML double-quoted scalars, so values with quotes or colons need no extra escaping.
const q = (value) => (typeof value === 'number' ? String(value) : JSON.stringify(value));
const map = (entries) => entries.map(([key, value]) => `  ${key}: ${q(value)}`).join('\n');

const description = readme.split('\n\n')[1].replace(/\s+/g, ' ').match(/^(.+?\.)\s/)[1];
const typography = tokens.type.groups.flatMap((g) => g.styles).map((s) => [
  `  ${s.name}:`,
  `    fontFamily: ${q(tokens.type.families[s.family ?? 'sans'] ?? tokens.type.families.sans)}`,
  // tokens.json keeps the clamp() ceiling; the real CSS value is recorded in usage.
  `    fontSize: ${q(s.usage.match(/clamp\([^)]*\)/)?.[0] ?? s.fontSize)}`,
  `    fontWeight: ${q(s.fontWeight)}`,
  `    lineHeight: ${q(s.lineHeight)}`,
  `    letterSpacing: ${q(s.letterSpacing ?? 'normal')}`,
].join('\n')).join('\n');

const frontmatter = [
  '---',
  '# GENERATED by scripts/docs/build-design-md.mjs from design-system/tokens.json and design-system/README.md; edit those, not this file.',
  `name: ${q(tokens.name)}`,
  `description: ${q(description)}`,
  'colors:', map(tokens.color.tokens.map((t) => [t.name, t.value])),
  'typography:', typography,
  'rounded:', map(tokens.radius.tokens.map((t) => [t.name.replace(/^radius-/, ''), t.value])),
  'spacing:', map(tokens.spacing.tokens.map((t) => [t.name, t.value])),
  '---',
].join('\n');

// README links are relative to design-system/; DESIGN.md sits at the repo root.
const body = readme
  .replace(/^# .*$/m, `# ${title}`)
  .replace(/\]\((?!https?:|#)([^)#]*)(#[^)]*)?\)/g, (_, path, hash = '') => `](${posix.normalize(posix.join('design-system', path))}${hash})`);

const sidecar = {
  schemaVersion: 2,
  title,
  extensions: { shadows: tokens.shadow.tokens.map((t) => ({ name: t.name, value: t.value, purpose: t.usage })) },
};

const outputs = new Map([
  ['DESIGN.md', `${frontmatter}\n\n${body}`],
  ['.impeccable/design.json', `${JSON.stringify(sidecar, null, 2)}\n`],
]);
const check = process.argv.includes('--check');
const stale = [...outputs].filter(([path, text]) => !existsSync(path) || readFileSync(path, 'utf8') !== text).map(([path]) => path);
if (check && stale.length) {
  console.error(`${stale.join(', ')} lệch design-system/; sửa design-system/ rồi chạy node scripts/docs/build-design-md.mjs`);
  process.exit(1);
}
if (!check) for (const [path, text] of outputs) writeFileSync(path, text);
console.log(`DESIGN.md ${check ? 'khớp' : 'đã sinh từ'} design-system/`);
