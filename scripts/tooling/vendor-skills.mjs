#!/usr/bin/env node
// Vendors the pinned agent skills into .claude/ so local, Remote Control and cloud
// Claude Code sessions load identical files. tooling-versions.json is the only input.
//
//   node scripts/tooling/vendor-skills.mjs              write .claude/skills, .claude/references, lock
//   node scripts/tooling/vendor-skills.mjs --check      fail if the committed tree differs from the pins
//   node scripts/tooling/vendor-skills.mjs --compare D  fail if skills in D differ from the lock
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const pins = JSON.parse(readFileSync(join(root, "tooling-versions.json"), "utf8"));
const claudeDir = join(root, ".claude");
const lockPath = join(claudeDir, "skills.lock.json");
const cacheDir = join(root, ".tooling", "skill-sources");

// Same selection the global Codex stack used: every skill folder that has a SKILL.md.
const SOURCES = [
  { repo: "addyosmani/agent-skills", skills: "skills", references: "references" },
  { repo: "ayghri/i-have-adhd", skill: "skills/i-have-adhd" },
  { repo: "juliusbrussee/caveman", skills: "skills" },
  { repo: "pbakaus/impeccable", skill: ".agents/skills/impeccable" },
  { repo: "dietrichgebert/ponytail", skills: "skills" },
];

function git(args, cwd) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function checkout(repo) {
  const commit = pins.repositories[repo];
  const url = pins.repository_urls[repo];
  if (!commit || !url) throw new Error(`tooling-versions.json has no pin for ${repo}`);
  const dir = join(cacheDir, repo.replace("/", "__"));
  if (!existsSync(join(dir, ".git"))) {
    mkdirSync(cacheDir, { recursive: true });
    git(["clone", "--quiet", "--filter=blob:none", "--no-checkout", url, dir]);
  }
  let head = "";
  try { head = git(["rev-parse", "HEAD"], dir); } catch { /* fresh clone without checkout */ }
  if (head !== commit) {
    try { git(["cat-file", "-e", `${commit}^{commit}`], dir); } catch { git(["fetch", "--quiet", "origin"], dir); }
    git(["-c", "advice.detachedHead=false", "checkout", "--quiet", "--force", "--detach", commit], dir);
  }
  return { dir, commit };
}

function files(dir) {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(dir, join(entry.parentPath ?? entry.path, entry.name)).split(sep).join("/"))
    .sort();
}

// Line endings are normalized so a Windows copy and a Linux checkout hash the same.
function treeHash(dir) {
  const hash = createHash("sha256");
  for (const file of files(dir)) {
    hash.update(`${file}\0`);
    hash.update(readFileSync(join(dir, file)).toString("latin1").replaceAll("\r\n", "\n"));
    hash.update("\0");
  }
  return hash.digest("hex");
}

function collect() {
  const skills = {};
  const references = [];
  for (const source of SOURCES) {
    const { dir, commit } = checkout(source.repo);
    const folders = source.skill
      ? [source.skill]
      : readdirSync(join(dir, source.skills), { withFileTypes: true })
          .filter((entry) => entry.isDirectory() && existsSync(join(dir, source.skills, entry.name, "SKILL.md")))
          .map((entry) => `${source.skills}/${entry.name}`);
    for (const folder of folders) {
      const name = folder.split("/").pop();
      if (skills[name]) throw new Error(`Skill name collision: ${name} (${skills[name].repo}, ${source.repo})`);
      skills[name] = { repo: source.repo, commit, path: folder, from: join(dir, folder) };
    }
    if (source.references) references.push({ repo: source.repo, commit, path: source.references, from: join(dir, source.references) });
  }
  return { skills, references };
}

function lockOf({ skills, references }) {
  const entry = ({ repo, commit, path, from }) => ({ repo, commit, path, sha256: treeHash(from) });
  return {
    schema: 1,
    note: "Generated by scripts/tooling/vendor-skills.mjs from tooling-versions.json. Do not edit .claude/skills by hand.",
    skills: Object.fromEntries(Object.keys(skills).sort().map((name) => [name, entry(skills[name])])),
    references: references.map(entry)[0] ?? null,
  };
}

function readLock() {
  if (!existsSync(lockPath)) throw new Error(`${relative(root, lockPath)} is missing; run node scripts/tooling/vendor-skills.mjs`);
  return JSON.parse(readFileSync(lockPath, "utf8"));
}

function diff(lock, skillsDir, referencesDir) {
  const problems = [];
  for (const [name, { sha256 }] of Object.entries(lock.skills)) {
    const dir = join(skillsDir, name);
    if (!existsSync(dir)) problems.push(`missing ${name}`);
    else if (treeHash(dir) !== sha256) problems.push(`changed ${name}`);
  }
  if (lock.references && referencesDir) {
    if (!existsSync(referencesDir)) problems.push("missing references");
    else if (treeHash(referencesDir) !== lock.references.sha256) problems.push("changed references");
  }
  return problems;
}

function write() {
  const collected = collect();
  const lock = lockOf(collected);
  const skillsDir = join(claudeDir, "skills");
  const previous = existsSync(lockPath) ? Object.keys(readLock().skills) : [];
  for (const name of previous) rmSync(join(skillsDir, name), { recursive: true, force: true });
  for (const [name, { from }] of Object.entries(collected.skills)) {
    rmSync(join(skillsDir, name), { recursive: true, force: true });
    cpSync(from, join(skillsDir, name), { recursive: true });
  }
  rmSync(join(claudeDir, "references"), { recursive: true, force: true });
  for (const { from } of collected.references) cpSync(from, join(claudeDir, "references"), { recursive: true });
  writeFileSync(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(`Vendored ${Object.keys(lock.skills).length} skills into .claude/skills.`);
}

function check() {
  const expected = lockOf(collect());
  const lock = readLock();
  const problems = diff(lock, join(claudeDir, "skills"), join(claudeDir, "references"));
  const strip = (l) => JSON.stringify({ skills: l.skills, references: l.references });
  if (strip(expected) !== strip(lock)) problems.push("skills.lock.json does not match tooling-versions.json pins");
  const unmanaged = readdirSync(join(claudeDir, "skills")).filter((name) => !lock.skills[name] && statSync(join(claudeDir, "skills", name)).isDirectory());
  if (unmanaged.length) problems.push(`unmanaged skill folders: ${unmanaged.join(", ")}`);
  report(problems, "vendored .claude/skills match the pins");
}

function compare(target) {
  const dir = resolve(target);
  report(diff(readLock(), dir, join(dir, "..", "references")), `${dir} matches .claude/skills.lock.json`);
}

function report(problems, ok) {
  if (problems.length) {
    console.error(`Skill drift:\n- ${problems.join("\n- ")}\nFix: node scripts/tooling/vendor-skills.mjs, commit, then pnpm tooling:bootstrap.`);
    process.exit(1);
  }
  console.log(`PASS ${ok}.`);
}

const [mode, arg] = process.argv.slice(2);
if (mode === "--check") check();
else if (mode === "--compare" && arg) compare(arg);
else if (!mode) write();
else {
  console.error("Usage: vendor-skills.mjs [--check | --compare <skills-dir>]");
  process.exit(2);
}
